"""Generate the packaged locale from reviewable UTF-8 TSV files (stdlib only)."""
from pathlib import Path
import json
import re
root = Path(__file__).resolve().parents[2]
def read(name):
    result = {}
    for number, line in enumerate((Path(__file__).parent / name).read_text(encoding='utf-8').splitlines(), 1):
        if not line or line.startswith('#'): continue
        en, ru = (value.replace(r'\n', '\n') for value in line.split('\t', 1))
        assert re.findall(r'%[ds]', en) == re.findall(r'%[ds]', ru), (name, number, 'format mismatch')
        assert en not in result or result[en] == ru, (name, number, 'conflicting duplicate')
        result[en] = ru
    return result
ui, names = read('ruRU.tsv'), read('client_names_ruRU.tsv')
quote = lambda s: json.dumps(s, ensure_ascii=False)
lines = ['-- Generated by Tools/Localization/build.py; edit the TSV sources.', 'local _, FN = ...']
for field, values in [('locales', ui), ('clientNames', names)]:
    lines += ['FN.'+field+'.ruRU = {']
    lines += ['    ['+quote(en)+'] = '+quote(ru)+',' for en, ru in sorted(values.items())]
    lines += ['}', '']
(root/'Locales').mkdir(exist_ok=True)
(root/'Locales/ruRU.lua').write_text('\n'.join(lines), encoding='utf-8')
print('Generated:', len(ui), 'UI phrases;', len(names), 'proper names')
